//! Codepoint range tables from [RFC 3454] (stringprep), as used by the
//! SASLprep profile in [RFC 4013].
//!
//! Transcribed verbatim from PostgreSQL's `src/common/saslprep.c` so that this
//! module accepts and rejects exactly the same passwords the server does. In
//! particular the A.1 table is frozen at Unicode 3.2, which is what RFC 3454
//! specifies and what PostgreSQL ships, even though the normalization step
//! uses current Unicode data.
//!
//! [RFC 3454]: https://www.rfc-editor.org/rfc/rfc3454
//! [RFC 4013]: https://www.rfc-editor.org/rfc/rfc4013

const std = @import("std");

/// An inclusive `[first, last]` codepoint range.
pub const Range = struct { first: u21, last: u21 };

/// Ranges are sorted and non-overlapping, so a binary search suffices.
pub fn contains(ranges: []const Range, cp: u21) bool {
    var lo: usize = 0;
    var hi: usize = ranges.len;
    while (lo < hi) {
        const mid = lo + (hi - lo) / 2;
        if (cp < ranges[mid].first) {
            hi = mid;
        } else if (cp > ranges[mid].last) {
            lo = mid + 1;
        } else {
            return true;
        }
    }
    return false;
}


