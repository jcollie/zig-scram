test "tables are sorted and non-overlapping" {
    for ([_][]const Range{
        non_ascii_space,
        commonly_mapped_to_nothing,
        prohibited_output,
        unassigned,
        rand_al_cat,
        l_cat,
    }) |table| {
        for (table, 0..) |range, i| {
            try std.testing.expect(range.first <= range.last);
            if (i > 0) try std.testing.expect(table[i - 1].last < range.first);
        }
    }
}

test "contains" {
    try std.testing.expect(contains(non_ascii_space, 0x00A0));
    try std.testing.expect(contains(non_ascii_space, 0x2005));
    try std.testing.expect(!contains(non_ascii_space, 0x0020));
    try std.testing.expect(contains(commonly_mapped_to_nothing, 0x00AD));
    try std.testing.expect(contains(prohibited_output, 0x0000));
    try std.testing.expect(contains(prohibited_output, 0x007F));
    try std.testing.expect(!contains(prohibited_output, 0x0041));
    try std.testing.expect(contains(rand_al_cat, 0x05D0));
    try std.testing.expect(contains(l_cat, 0x0041));
    try std.testing.expect(!contains(l_cat, 0x05D0));
}
